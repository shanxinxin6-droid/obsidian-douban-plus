import esbuild from "esbuild";
import process from "process";
import builtins from 'builtin-modules'
import {mkdir, writeFile} from 'node:fs/promises';

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Douban Plus - maintained by shanxinxin6-droid.
Based on Wanxp/obsidian-douban; original authors and contributors retain their rights.
SPDX-License-Identifier: GPL-3.0-only
Source and license: https://github.com/shanxinxin6-droid/obsidian-douban-plus
Releases include LICENSE, NOTICE, SOURCE.md and THIRD_PARTY_NOTICES.txt.
*/
`;

const prod = (process.argv[2] === 'production');

esbuild.build({
	banner: {
		js: banner,
	},
	entryPoints: ['src/org/wanxp/main.ts'],
	bundle: true,
	metafile: prod,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/closebrackets',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/comment',
		'@codemirror/fold',
		'@codemirror/gutter',
		'@codemirror/highlight',
		'@codemirror/history',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/matchbrackets',
		'@codemirror/panel',
		'@codemirror/rangeset',
		'@codemirror/rectangular-selection',
		'@codemirror/searcher',
		'@codemirror/state',
		'@codemirror/stream-parser',
		'@codemirror/text',
		'@codemirror/tooltip',
		'@codemirror/view',
		...builtins],
	format: 'cjs',
	watch: !prod,
	target: 'es2016',
	logLevel: "info",
	sourcemap: prod ? false : true,
	treeShaking: true,
	outfile: 'main.js',
	// minify: true
}).then(async result => {
	if (prod) {
		await mkdir('dist', {recursive: true});
		await writeFile('dist/build-meta.json', JSON.stringify(result.metafile));
	}
}).catch(error => { console.error(error); process.exit(1); });
